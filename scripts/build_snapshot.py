"""Turn a County List Agent run into the masked snapshot Deal Desk ships with: shared/snapshot.ts.

    python scripts/build_snapshot.py [path/to/out/montgomery-tn/<date>]

No owner names or mailing addresses leave this script, and house numbers are masked ("9•• Swift Dr"), so the
snapshot is safe in a public repo and a hosted demo. Sale-date signals (within 30 days, passed) are worked out live
in the app from the sale date, so they stay right as the days go by.
"""
import json, re, sys
from datetime import date, datetime
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
AGENT_OUT = ROOT.parent.parent / "county-list-agent" / "out" / "montgomery-tn"
SIGNAL_OF = {
    "Foreclosure sale scheduled": "foreclosure",
    "Foreclosure sale date has passed (check if postponed)": "foreclosure",
    "Sold at tax sale, can still redeem": "tax_sale",
    "Estate, heirs or several co-owners on the deed": "inherited",
    "Owner lives out of state": "out_of_state",
    "Owner doesn't live there": "absentee",
    "Owned 20+ years": "long_owned",
    "Built before 1960": "old_house",
    "Land only, no house": "land_only",
}


def mask(addr):
    m = re.match(r"(\d)(\d*)\s+(.*)", addr or "")
    return f"{m.group(1)}{'•' * len(m.group(2))} {m.group(3).title()}" if m else (addr or "").title()


def safe_note(note):
    """Keep the facts (paper, dates, amounts); drop buyer and owner names."""
    note = re.sub(r" to [^;|]+?;", ";", note)
    return note.strip()


def rows(ws):
    for r in list(ws.iter_rows(min_row=2)):
        v = [c.value for c in r]
        link = r[13].hyperlink.target if r[13].hyperlink else ""
        m = re.search(r"q=([-\d.]+),([-\d.]+)", link or "")
        yield v, (float(m.group(1)), float(m.group(2))) if m else (None, None)


def lead(i, prefix, v, latlon):
    why = [w.strip() for w in (v[1] or "").split(";") if w.strip()]
    signals = sorted({SIGNAL_OF[w] for w in why if w in SIGNAL_OF})
    sale = v[6].date().isoformat() if isinstance(v[6], datetime) else None
    notes = [safe_note(n) for n in (v[11] or "").split(" | ") if n.strip()]
    return {"id": f"{prefix}{i}", "addr": mask(v[2]), "city": (v[3] or "").title(), "signals": signals,
            "value": int(v[7] or 0), "year": int(v[8] or 0), "sale": sale, "lat": latlon[0], "lon": latlon[1], "notes": notes}


def main():
    run = Path(sys.argv[1]) if len(sys.argv) > 1 else sorted(AGENT_OUT.iterdir())[-1]
    wb = openpyxl.load_workbook(run / "leads.xlsx")
    hot = [lead(i + 1, "L", v, ll) for i, (v, ll) in enumerate(rows(wb["Hot leads"]))]
    quiet = [lead(i + 1, "Q", v, ll) for i, (v, ll) in enumerate(rows(wb["Quiet distress"]))]
    sources = {r[0]: r[3] for r in wb["Sources"].iter_rows(min_row=2, values_only=True)}
    to_check = wb["Check by hand"].max_row - 1
    snap = {
        "county": "Montgomery County, TN", "city": "Clarksville", "ranOn": run.name, "seconds": 53,
        "counts": {"parcels": next((v for k, v in sources.items() if "parcel" in k.lower()), 0),
                   "notices": next((v for k, v in sources.items() if "Foreclosure" in k), 0),
                   "taxSale": next((v for k, v in sources.items() if "Tax-sale" in k), 0), "toCheck": to_check},
        "leads": hot, "quiet": quiet,
    }
    out = ROOT / "shared" / "snapshot.ts"
    out.write_text("// Generated by scripts/build_snapshot.py from a County List Agent run. Masked: no owner names, house numbers hidden.\n"
                   "import type { Snapshot } from \"./deal.js\";\n\n"
                   f"export const SNAPSHOT: Snapshot = {json.dumps(snap, ensure_ascii=False, indent=1)};\n", encoding="utf-8")
    print(f"{out}: {len(hot)} hot, {len(quiet)} quiet, run {run.name}")


if __name__ == "__main__":
    main()
